// Copies the self-hosted font subsets (latin, latin-ext, vietnamese) into
// src/footage/static/fonts/ and writes fonts.css with matching @font-face rules.
import { readFileSync, writeFileSync, mkdirSync, copyFileSync } from "node:fs";
import { dirname, join, basename } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "..", "..", "src", "footage", "static", "fonts");
mkdirSync(out, { recursive: true });
const modules = join(here, "..", "node_modules");
const SUBSETS = ["latin", "latin-ext", "vietnamese"];
const sources = [
  // [package dir, css files]
  ["@fontsource-variable/newsreader", ["opsz.css", "opsz-italic.css"]],
  ["@fontsource/jetbrains-mono", ["400.css", "500.css", "700.css"]],
  ["@fontsource/inter", ["400.css", "500.css"]],
];
let css = "/* Generated by frontend/scripts/copy-fonts.mjs — do not edit. */\n";
for (const [pkg, files] of sources) {
  for (const file of files) {
    const text = readFileSync(join(modules, pkg, file), "utf8");
    for (const block of text.split("/*").slice(1)) {
      const token = block.slice(0, block.indexOf("*/")).trim();
      const subset = ["latin-ext", "vietnamese", "latin"].find((s) => token.includes(`-${s}-`));
      if (!subset || !SUBSETS.includes(subset)) continue;
      let rule = block.slice(block.indexOf("@font-face"));
      rule = rule.replace(/url\(\.\/files\/([^)]+\.woff2)\) format\('woff2(?:-variations)?'\)(,\s*url\([^)]+\) format\('woff'\))?/g,
        (_m, name) => {
          copyFileSync(join(modules, pkg, "files", name), join(out, basename(name)));
          return `url(./${basename(name)}) format('woff2')`;
        });
      css += rule.trim() + "\n";
    }
  }
}
writeFileSync(join(out, "fonts.css"), css);
console.log("fonts ->", out);
